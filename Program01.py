# โปรแกรมคำนวณพื้นที่รูปสี่เหลี่ยมมุมฉาก

print("โปรแกรมคำนวณพื้นที่")

print("1. สี่เหลี่ยม")
print("2. สามเหลี่ยม")
print("3. วงกลม")

choice = int(input("เลือกรูปทรง: "))

if choice == 1:
    กว้าง = float(input("กรอกความกว้าง: "))
    ยาว = float(input("กรอกความยาว: "))
    พื้นที่ = กว้าง * ยาว
    print("พื้นที่ =", พื้นที่)

elif choice == 2:
    ฐาน = float(input("กรอกฐาน: "))
    สูง = float(input("กรอกความสูง: "))
    พื้นที่ = 0.5 * ฐาน * สูง
    print("พื้นที่ =", พื้นที่)

elif choice == 3:
    รัศมี = float(input("กรอกรัศมี: "))
    พื้นที่ = 3.14 * รัศมี * รัศมี
    print("พื้นที่ =", พื้นที่)

else:
    print("กรุณาเลือก 1-3")
